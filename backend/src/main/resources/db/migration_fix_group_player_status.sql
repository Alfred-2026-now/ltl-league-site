-- ============================================================
-- 修复：登峰组/涅槃组选手的状态从"自由人"(3)改为"在职"(1)
-- 原因：选手已分组到登峰/涅槃组，但 status 仍为 3（自由人），
--       导致后台编辑时"队伍"下拉被禁用、后端校验"自由人不能属于队伍"，
--       无法在后台调整选手组别。
-- ============================================================

UPDATE `players`
SET `status` = 1
WHERE `deleted` = 0
  AND `team_id` IN (
    SELECT `id` FROM `teams` WHERE `name` IN ('登峰组', '涅槃组') AND `deleted` = 0
  );
